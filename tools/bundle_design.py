# -*- coding: utf-8 -*-
"""Сборка GAME_DESIGN → bundle.json + Luau-модуль Config/Bundle.lua (Ф1.13).

Игра не парсит JSON в рантайме: получает готовые Luau-таблицы.

Запуск: python -X utf8 tools/bundle_design.py
"""
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "GAME_DESIGN"
OUT_JSON = DESIGN / "bundle.json"
OUT_LUA = ROOT / "ROBLOX_IMPLEMENTATION" / "src" / "ReplicatedStorage" / "TH_Shared" / "Config" / "Bundle.lua"
STYLUA = Path(r"D:\DSH\20-tools\stylua\stylua.exe")

KEYS = {
    "constants.json": "constants",
    "Factions.json": "factions",
    "Heroes.json": "heroes",
    "Goods.json": "goods",
    "Prices.json": "prices",
    "Ships.json": "ships",
    "Professions.json": "professions",
    "Routes.json": "routes",
    "Buildings.json": "buildings",
    "Weather.json": "weather",
    "NPC.json": "npc",
    "Quests.json": "quests",
}


def luau(value, indent: int = 1) -> str:
    pad = "    " * indent
    pad_in = "    " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f'{pad_in}["{k}"] = {luau(v, indent + 1)}' for k, v in value.items()]
        return "{\n" + ",\n".join(items) + f"\n{pad}}}"
    if isinstance(value, list):
        if not value:
            return "{}"
        items = [f"{pad_in}{luau(v, indent + 1)}" for v in value]
        return "{\n" + ",\n".join(items) + f"\n{pad}}}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nil"
    if isinstance(value, (int, float)):
        return repr(value)
    s = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def main() -> None:
    bundle = {}
    missing = []
    for fname, key in KEYS.items():
        p = DESIGN / fname
        if not p.exists():
            missing.append(fname)
            continue
        bundle[key] = json.loads(p.read_text(encoding="utf-8"))

    OUT_JSON.write_text(json.dumps(bundle, ensure_ascii=False, indent=1), encoding="utf-8")

    header = (
        "-- AUTOGENERATED by tools/bundle_design.py — НЕ ПРАВИТЬ РУКАМИ.\n"
        "-- Источник: GAME_DESIGN/*.json. Пересборка: python -X utf8 tools/bundle_design.py\n\n"
    )
    OUT_LUA.parent.mkdir(parents=True, exist_ok=True)
    OUT_LUA.write_text(header + "return " + luau(bundle) + "\n", encoding="utf-8")

    if STYLUA.exists():
        subprocess.run([str(STYLUA), str(OUT_LUA)], check=False)

    size = len(bundle)
    print(f"OK {OUT_JSON} | блоков: {size}" + (f" | нет: {missing}" if missing else ""))
    print(f"OK {OUT_LUA}")


if __name__ == "__main__":
    main()
